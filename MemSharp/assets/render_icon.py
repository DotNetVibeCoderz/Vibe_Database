"""Render the MemSharp package icon.

Writes icon.svg, icon.png (512, NuGet's PackageIcon), icon-128.png and icon-64.png next to this
script. Both the SVG and the PNGs are produced from the geometry constants below, so the vector
source and the raster cannot drift apart; edit the constants, never the SVG by hand.

The design: a database stack of three amber discs on the demo's night-navy tile, split by a
lightning bolt cut out as negative space. The cut is the point -- it shards every disc into two
pieces, so "sharded" and "fast" are one motif rather than two decorations that would turn to mush
at 32px.

Only Pillow is required. Drawing happens at 4x and is downsampled with LANCZOS for anti-aliasing.

    python -I assets/render_icon.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

OUT = Path(__file__).resolve().parent

# ---------------------------------------------------------------------------------------------
# Palette -- from samples/MemSharp.TradingDemo/Palette.axaml. Amber is the colour that identifies
# MemSharp across the CLI and docs; the light/dark amber stops are shades of it for the cylinder.
# ---------------------------------------------------------------------------------------------
TILE_TOP = "#1A2536"      # PanelRaised
TILE_BOTTOM = "#0B111C"   # Ink
TILE_RULE = "#24314A"     # Rule -- hairline inner border
AMBER = "#F0A830"         # Amber
AMBER_LIGHT = "#FFCF70"   # highlight on the top face
AMBER_DARK = "#B9741A"    # shade at the cylinder's flanks
BOLT_TOP = "#FFFFFF"
BOLT_BOTTOM = "#EDF3FB"   # TextBright

# ---------------------------------------------------------------------------------------------
# Geometry, in a 512 x 512 design space.
# ---------------------------------------------------------------------------------------------
SIZE = 512
TILE_RADIUS = 112
RULE_WIDTH = 4

CX = 256                  # stack centre line
RX, RY = 138, 40          # disc ellipse radii
SLAB = 60                 # side-band height of each disc
GAP = 26                  # vertical gap between discs (reads as ~1.6px at 32px)
DISCS = 3
STACK_TOP = 108           # top of the top ellipse
FIRST_Y = STACK_TOP + RY  # centre of the top disc's top ellipse
PITCH = SLAB + GAP

# Lightning bolt, clockwise from the top-left corner.
BOLT = [
    (302, 50), (364, 50), (306, 214), (362, 214),
    (204, 464), (250, 290), (192, 290),
]
HALO = 14                 # width of the negative-space cut around the bolt

SUPERSAMPLE = 4


def disc_centres() -> list[int]:
    return [FIRST_Y + i * PITCH for i in range(DISCS)]


# ---------------------------------------------------------------------------------------------
# SVG
# ---------------------------------------------------------------------------------------------
def band_path(y: float) -> str:
    """Side band of a disc: the region between its top ellipse's lower arc and its bottom one."""
    l, r = CX - RX, CX + RX
    return (f"M{l},{y} A{RX},{RY} 0 0 0 {r},{y} L{r},{y + SLAB} "
            f"A{RX},{RY} 0 0 1 {l},{y + SLAB} Z")


def build_svg() -> str:
    pts = " ".join(f"{x},{y}" for x, y in BOLT)
    bands = "\n    ".join(f'<path d="{band_path(y)}"/>' for y in disc_centres())
    top_y = disc_centres()[0]
    half = RULE_WIDTH / 2
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
  <!-- MemSharp package icon. Generated by render_icon.py from the same constants as the PNGs. -->
  <title>MemSharp</title>
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="{SIZE}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{TILE_TOP}"/>
      <stop offset="1" stop-color="{TILE_BOTTOM}"/>
    </linearGradient>
    <linearGradient id="side" x1="{CX - RX}" y1="0" x2="{CX + RX}" y2="0" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{AMBER_DARK}"/>
      <stop offset="0.42" stop-color="{AMBER}"/>
      <stop offset="1" stop-color="{AMBER_DARK}"/>
    </linearGradient>
    <linearGradient id="face" x1="0" y1="{top_y - RY}" x2="0" y2="{top_y + RY}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{AMBER_LIGHT}"/>
      <stop offset="1" stop-color="{AMBER}"/>
    </linearGradient>
    <linearGradient id="bolt" x1="0" y1="{BOLT[0][1]}" x2="0" y2="{BOLT[4][1]}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{BOLT_TOP}"/>
      <stop offset="1" stop-color="{BOLT_BOTTOM}"/>
    </linearGradient>
    <!-- The bolt plus its halo is cut out of the discs, so the tile shows through. -->
    <mask id="cut" maskUnits="userSpaceOnUse" x="0" y="0" width="{SIZE}" height="{SIZE}">
      <rect width="{SIZE}" height="{SIZE}" fill="#fff"/>
      <polygon points="{pts}" fill="#000" stroke="#000" stroke-width="{2 * HALO}" stroke-linejoin="round"/>
    </mask>
  </defs>

  <rect width="{SIZE}" height="{SIZE}" rx="{TILE_RADIUS}" fill="url(#tile)"/>
  <rect x="{half}" y="{half}" width="{SIZE - RULE_WIDTH}" height="{SIZE - RULE_WIDTH}" rx="{TILE_RADIUS - half}"
        fill="none" stroke="{TILE_RULE}" stroke-width="{RULE_WIDTH}"/>

  <g mask="url(#cut)">
    <g fill="url(#side)">
    {bands}
    </g>
    <ellipse cx="{CX}" cy="{top_y}" rx="{RX}" ry="{RY}" fill="url(#face)"/>
  </g>

  <polygon points="{pts}" fill="url(#bolt)" stroke-linejoin="round"/>
</svg>
"""


# ---------------------------------------------------------------------------------------------
# Raster (Pillow)
# ---------------------------------------------------------------------------------------------
S = SUPERSAMPLE
W = SIZE * S


def rgb(hex_: str) -> tuple[int, int, int]:
    h = hex_.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def lerp(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def gradient(stops: list[tuple[float, str]], start: float, end: float, vertical: bool) -> Image.Image:
    """Full-canvas linear gradient, matching SVG userSpaceOnUse semantics (clamped past the ends)."""
    cols = [(o, rgb(c)) for o, c in stops]
    line = []
    for p in range(W):
        t = ((p + 0.5) / S - start) / (end - start)
        t = min(max(t, 0.0), 1.0)
        for (o0, c0), (o1, c1) in zip(cols, cols[1:]):
            if t <= o1:
                line.append(lerp(c0, c1, 0 if o1 == o0 else (t - o0) / (o1 - o0)))
                break
        else:
            line.append(cols[-1][1])
    if vertical:
        strip = Image.new("RGB", (1, W))
    else:
        strip = Image.new("RGB", (W, 1))
    strip.putdata(line)
    return strip.resize((W, W), Image.NEAREST)


def sc(v: float) -> float:
    return v * S


def ellipse_box(cy: float) -> tuple[float, float, float, float]:
    return (sc(CX - RX), sc(cy - RY), sc(CX + RX), sc(cy + RY))


def mask() -> tuple[Image.Image, ImageDraw.ImageDraw]:
    m = Image.new("L", (W, W), 0)
    return m, ImageDraw.Draw(m)


def render() -> Image.Image:
    canvas = Image.new("RGBA", (W, W), (0, 0, 0, 0))

    # Tile
    tile_mask, d = mask()
    d.rounded_rectangle((0, 0, W - 1, W - 1), radius=sc(TILE_RADIUS), fill=255)
    tile = gradient([(0, TILE_TOP), (1, TILE_BOTTOM)], 0, SIZE, vertical=True)
    canvas.paste(tile, (0, 0), tile_mask)

    rule_mask, d = mask()
    d.rounded_rectangle((0, 0, W - 1, W - 1), radius=sc(TILE_RADIUS), fill=255)
    inset = sc(RULE_WIDTH)
    d.rounded_rectangle((inset, inset, W - 1 - inset, W - 1 - inset),
                        radius=sc(TILE_RADIUS - RULE_WIDTH), fill=0)
    canvas.paste(Image.new("RGB", (W, W), rgb(TILE_RULE)), (0, 0), rule_mask)

    # Cut: bolt polygon dilated by HALO (round joins, as in the SVG stroke).
    cut, d = mask()
    pts = [(sc(x), sc(y)) for x, y in BOLT]
    d.polygon(pts, fill=255)
    d.line(pts + [pts[0]], fill=255, width=round(sc(2 * HALO)), joint="curve")
    r = sc(HALO)
    for x, y in pts:
        d.ellipse((x - r, y - r, x + r, y + r), fill=255)
    keep = ImageChops.invert(cut)

    # Disc side bands
    bands, d = mask()
    for y in disc_centres():
        band, bd = mask()
        bd.rectangle((sc(CX - RX), sc(y), sc(CX + RX), sc(y + SLAB)), fill=255)
        bd.ellipse(ellipse_box(y + SLAB), fill=255)
        bd.ellipse(ellipse_box(y), fill=0)
        bands = ImageChops.lighter(bands, band)
    side = gradient([(0, AMBER_DARK), (0.42, AMBER), (1, AMBER_DARK)], CX - RX, CX + RX, vertical=False)
    canvas.paste(side, (0, 0), ImageChops.multiply(bands, keep))

    # Top face of the top disc
    top_y = disc_centres()[0]
    face_mask, d = mask()
    d.ellipse(ellipse_box(top_y), fill=255)
    face = gradient([(0, AMBER_LIGHT), (1, AMBER)], top_y - RY, top_y + RY, vertical=True)
    canvas.paste(face, (0, 0), ImageChops.multiply(face_mask, keep))

    # Bolt
    bolt_mask, d = mask()
    d.polygon(pts, fill=255)
    bolt = gradient([(0, BOLT_TOP), (1, BOLT_BOTTOM)], BOLT[0][1], BOLT[4][1], vertical=True)
    canvas.paste(bolt, (0, 0), bolt_mask)

    # Keep the corners fully transparent: the tile mask is the final alpha.
    canvas.putalpha(ImageChops.multiply(canvas.getchannel("A"), tile_mask))
    return canvas


def main() -> None:
    (OUT / "icon.svg").write_text(build_svg(), encoding="utf-8", newline="\n")
    big = render()
    for size, name in ((512, "icon.png"), (128, "icon-128.png"), (64, "icon-64.png")):
        # Downsample from the supersampled master each time rather than chaining, so each size
        # gets one LANCZOS pass. A light unsharp at the small sizes keeps the bolt's edges crisp.
        img = big.resize((size, size), Image.LANCZOS)
        if size <= 128:
            img = img.filter(ImageFilter.UnsharpMask(radius=0.6, percent=60, threshold=0))
        img.save(OUT / name, optimize=True)
        print(f"wrote {name} ({size}x{size}, {(OUT / name).stat().st_size} bytes)")
    print("wrote icon.svg")


if __name__ == "__main__":
    main()
