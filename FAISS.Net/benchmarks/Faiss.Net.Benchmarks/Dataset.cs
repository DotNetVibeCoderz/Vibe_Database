using Faiss.Net;

namespace Faiss.Net.Benchmarks;

/// <summary>
/// Generates the benchmark dataset and reads and writes it in <c>.fvecs</c> / <c>.ivecs</c> — the
/// formats the standard ANN datasets (SIFT, GIST, DEEP) ship in, and the ones Python FAISS examples
/// already know how to load.
/// <para>
/// The two implementations must measure the same thing, and the only way to guarantee that is for
/// both to read the same bytes. The .NET side generates the vectors once and writes them to disk;
/// the Python benchmark reads those files rather than generating its own. Ground truth is computed
/// exactly, once, and shared too, so a recall difference between the two can only come from the
/// index, never from a different notion of what the right answer was.
/// </para>
/// <para>
/// Queries are held out of the same draw as the database. Generating them independently would make
/// them out-of-distribution, which depresses every approximate index by a large and uninteresting
/// margin and tells you nothing about the implementations being compared.
/// </para>
/// </summary>
public sealed class Dataset
{
    public required int Dimension { get; init; }
    public required int DatabaseSize { get; init; }
    public required int QueryCount { get; init; }
    public required int K { get; init; }

    public float[] Database { get; private set; } = [];
    public float[] Queries { get; private set; } = [];

    /// <summary>Exact neighbours, <c>QueryCount * K</c> ids.</summary>
    public long[] GroundTruth { get; private set; } = [];

    /// <summary>Generates the dataset in memory.</summary>
    public static Dataset Generate(int dimension, int databaseSize, int queryCount, int k, long seed = 1234)
    {
        var dataset = new Dataset
        {
            Dimension = dimension,
            DatabaseSize = databaseSize,
            QueryCount = queryCount,
            K = k,
        };

        var all = FaissNet.RandomClusteredVectors(
            databaseSize + queryCount, dimension,
            clusters: Math.Max(16, databaseSize / 250), spread: 0.06f, seed: seed);

        dataset.Database = all.AsSpan(0, databaseSize * dimension).ToArray();
        dataset.Queries = all.AsSpan(databaseSize * dimension, queryCount * dimension).ToArray();
        return dataset;
    }

    /// <summary>Computes exact ground truth with a flat index.</summary>
    public void ComputeGroundTruth()
    {
        var flat = new IndexFlatL2(Dimension);
        flat.Add(Database);
        GroundTruth = flat.Search(Queries, K).Labels;
    }

    /// <summary>Recall@k of a result against the stored ground truth.</summary>
    public double Recall(SearchResult result)
    {
        long found = 0, expected = 0;
        var truth = new HashSet<long>();
        for (int q = 0; q < QueryCount; q++)
        {
            truth.Clear();
            for (int i = 0; i < K; i++)
            {
                long id = GroundTruth[q * K + i];
                if (id >= 0) { truth.Add(id); expected++; }
            }
            var labels = result.LabelsFor(q);
            for (int i = 0; i < Math.Min(K, labels.Length); i++)
                if (labels[i] >= 0 && truth.Contains(labels[i])) found++;
        }
        return expected == 0 ? 0 : found / (double)expected;
    }

    // ------------------------------------------------------------ fvecs IO

    /// <summary>Writes database, queries and ground truth into <paramref name="directory"/>.</summary>
    public void Save(string directory)
    {
        Directory.CreateDirectory(directory);
        WriteFvecs(Path.Combine(directory, "base.fvecs"), Database, Dimension);
        WriteFvecs(Path.Combine(directory, "query.fvecs"), Queries, Dimension);
        WriteIvecs(Path.Combine(directory, "groundtruth.ivecs"), GroundTruth, K);

        File.WriteAllText(Path.Combine(directory, "dataset.json"),
            $$"""
            {
              "dimension": {{Dimension}},
              "database_size": {{DatabaseSize}},
              "query_count": {{QueryCount}},
              "k": {{K}},
              "note": "Generated by FAISS.Net. Both benchmark suites read these exact files."
            }
            """);
    }

    /// <summary>Loads a dataset previously written by <see cref="Save"/>.</summary>
    public static Dataset Load(string directory)
    {
        var (database, dimension) = ReadFvecs(Path.Combine(directory, "base.fvecs"));
        var (queries, queryDimension) = ReadFvecs(Path.Combine(directory, "query.fvecs"));
        if (dimension != queryDimension)
            throw new InvalidDataException($"Base is {dimension}-dimensional but queries are {queryDimension}.");

        var (truth, k) = ReadIvecs(Path.Combine(directory, "groundtruth.ivecs"));

        return new Dataset
        {
            Dimension = dimension,
            DatabaseSize = database.Length / dimension,
            QueryCount = queries.Length / dimension,
            K = k,
            Database = database,
            Queries = queries,
            GroundTruth = truth,
        };
    }

    /// <summary>fvecs: each record is an int32 dimension followed by that many float32 values.</summary>
    public static void WriteFvecs(string path, ReadOnlySpan<float> vectors, int dimension)
    {
        using var stream = new FileStream(path, FileMode.Create, FileAccess.Write, FileShare.None, 1 << 20);
        using var writer = new BinaryWriter(stream);
        int n = vectors.Length / dimension;
        for (int i = 0; i < n; i++)
        {
            writer.Write(dimension);
            for (int j = 0; j < dimension; j++) writer.Write(vectors[i * dimension + j]);
        }
    }

    public static (float[] Vectors, int Dimension) ReadFvecs(string path)
    {
        using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 1 << 20);
        using var reader = new BinaryReader(stream);
        int dimension = reader.ReadInt32();
        stream.Position = 0;

        long recordBytes = 4 + (long)dimension * 4;
        int n = (int)(stream.Length / recordBytes);
        var vectors = new float[(long)n * dimension];
        for (int i = 0; i < n; i++)
        {
            reader.ReadInt32(); // per-record dimension, already known
            for (int j = 0; j < dimension; j++) vectors[(long)i * dimension + j] = reader.ReadSingle();
        }
        return (vectors, dimension);
    }

    /// <summary>ivecs: the integer counterpart of fvecs, used for ground-truth ids.</summary>
    public static void WriteIvecs(string path, ReadOnlySpan<long> values, int k)
    {
        using var stream = new FileStream(path, FileMode.Create, FileAccess.Write, FileShare.None, 1 << 20);
        using var writer = new BinaryWriter(stream);
        int n = values.Length / k;
        for (int i = 0; i < n; i++)
        {
            writer.Write(k);
            for (int j = 0; j < k; j++) writer.Write((int)values[i * k + j]);
        }
    }

    public static (long[] Values, int K) ReadIvecs(string path)
    {
        using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 1 << 20);
        using var reader = new BinaryReader(stream);
        int k = reader.ReadInt32();
        stream.Position = 0;

        long recordBytes = 4 + (long)k * 4;
        int n = (int)(stream.Length / recordBytes);
        var values = new long[(long)n * k];
        for (int i = 0; i < n; i++)
        {
            reader.ReadInt32();
            for (int j = 0; j < k; j++) values[(long)i * k + j] = reader.ReadInt32();
        }
        return (values, k);
    }
}
